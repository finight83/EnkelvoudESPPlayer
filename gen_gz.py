#!/usr/bin/env python3
"""
gen_gz.py — pre-compress the EnkelvoudESPPlayer HTML page.

Since the config-fetch refactor (v1.1.2), the node's page is a single static
PROGMEM block (EVDSET_PAGE_HTML in EVDSET.h). That is exactly the shape the
server's gen_gz.py already handles, so this script is nearly identical.

Output goes to EVDSET_GZ.h as:
    EVDSET_HTML_GZ[]        - gzip stream of the page
    EVDSET_HTML_GZ_LEN      - its length in bytes

The sketch uses the synchronous WebServer, not AsyncWebServer. handleRoot()
in EVDPWeb.h serves EVDSET_HTML_GZ via the String-from-bytes path:

    String body((const char*)EVDSET_HTML_GZ, EVDSET_HTML_GZ_LEN);
    server.sendHeader("Content-Encoding", "gzip");
    server.send(200, "text/html; charset=utf-8", body);

That form lets the sync WebServer emit Content-Length. The older
setContentLength()+send("") path did not, on some arduino-esp32 cores.
"""
import gzip
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC  = HERE / "EVDSET.h"
DST  = HERE / "EVDSET_GZ.h"


def main():
    if not SRC.exists():
        raise SystemExit(f"ERROR: {SRC} not found (put gen_gz.py next to EVDSET.h)")

    src = SRC.read_text(encoding="utf-8").replace("\r", "")

    # Match the single EVDSET_PAGE_HTML raw-string block. DOTALL so the
    # regex spans newlines; non-greedy so it stops at the first )EVD.
    m = re.search(r'EVDSET_PAGE_HTML\[\]\s+PROGMEM\s*=\s*R"EVD\((.*?)\)EVD"', src, re.S)
    if not m:
        raise SystemExit(
            "ERROR: could not find `static const char EVDSET_PAGE_HTML[] PROGMEM = R\"EVD(...)EVD\"` in EVDSET.h. "
            "Did the config-fetch refactor not run, or did the block name change?"
        )

    html = m.group(1)
    if ")EVD" in html:
        raise SystemExit(
            "ERROR: the raw-string terminator )EVD appears inside the page body. "
            "EVDSET.h content contains the delimiter."
        )

    # mtime=0 zeroes the gzip header's MTIME field so regenerating without
    # changing EVDSET.h produces a byte-identical EVDSET_GZ.h. Without it,
    # every run embeds a fresh wall-clock timestamp and every rebuild is a
    # spurious diff.
    raw = html.encode("utf-8")
    # gzip.compress(..., mtime=0) requires Python >= 3.11. Debian 11 (3.9)
    # and Ubuntu 22.04 (3.10) raise TypeError on the mtime kwarg. GzipFile
    # has accepted mtime since Python 3.1 — use it directly for compat.
    import io
    _buf = io.BytesIO()
    with gzip.GzipFile(fileobj=_buf, mode="wb",
                       compresslevel=9, mtime=0) as _gzf:
        _gzf.write(raw)
    gz = _buf.getvalue()

    with DST.open("w", encoding="utf-8") as fh:
        fh.write("#pragma once\n")
        fh.write("// Auto-generated by gen_gz.py from EVDSET.h. Do not edit.\n")
        fh.write("// Regenerate with gen_gz.bat (or `python gen_gz.py`).\n")
        fh.write("#include <Arduino.h>\n\n")
        fh.write("static const uint8_t EVDSET_HTML_GZ[] PROGMEM = {\n")
        for i in range(0, len(gz), 16):
            chunk = gz[i:i + 16]
            fh.write("  " + ",".join(f"0x{b:02x}" for b in chunk) + ",\n")
        fh.write("};\n")
        fh.write(f"static const size_t EVDSET_HTML_GZ_LEN = {len(gz)};\n")

    print(f"raw {len(raw):6d} B  ->  gz {len(gz):6d} B "
          f"({100.0 * len(gz) / len(raw):.1f}%)")
    print(f"wrote {DST.name}")


if __name__ == "__main__":
    sys.exit(main())